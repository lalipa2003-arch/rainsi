const TRAMPOLINE_WASM_BYTES = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x06, 0x01, 0x60, 0x01, 0x7f, 0x01, 0x7f,
  0x02, 0x0a, 0x01, 0x03, 0x65, 0x6e, 0x76, 0x02, 0x63, 0x62, 0x00, 0x00,
  0x03, 0x02, 0x01, 0x00,
  0x07, 0x08, 0x01, 0x04, 0x63, 0x61, 0x6c, 0x6c, 0x00, 0x01,
  0x0a, 0x08, 0x01, 0x06, 0x00, 0x20, 0x00, 0x10, 0x00, 0x0b,
]);

let cachedModule: WebAssembly.Module | null = null;

function getTrampolineModule(): WebAssembly.Module {
  if (!cachedModule) {
    cachedModule = new WebAssembly.Module(TRAMPOLINE_WASM_BYTES);
  }
  return cachedModule;
}

export function createWasmCallback(callback: (luaState: number) => number): any {
  const mod = getTrampolineModule();
  const instance = new WebAssembly.Instance(mod, {
    env: {
      cb: callback,
    },
  });
  return instance.exports.call;
}
